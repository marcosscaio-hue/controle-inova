CREATE TABLE IF NOT EXISTS usuarios (
  id SERIAL PRIMARY KEY,
  cpf VARCHAR(11) NOT NULL UNIQUE,
  senha_hash VARCHAR(64) NOT NULL,
  nome VARCHAR(100),
  ativo BOOLEAN NOT NULL DEFAULT true,
  data_criacao TIMESTAMP NOT NULL DEFAULT NOW()
);

